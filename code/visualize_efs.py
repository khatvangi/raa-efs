#!/usr/bin/env python3
"""
EFS Core Visualization Protocol
================================
Generates PyMOL/ChimeraX scripts to visualize EFS core positions in protein structures.

Usage:
    python visualize_efs.py <protein_id> [--family PF00069]

Example:
    python visualize_efs.py A2QRF6 --family PF00069

Output:
    Creates pymol_viz/<protein_id>_efs.pml and _efs.cxc scripts
"""

import pandas as pd
import argparse
import os
import sys
from pathlib import Path

# efs core threshold (C20 = raw_score >= 5, which maps to core_score >= 20)
EFS_CORE_THRESHOLD = 20

def find_core_scores(protein_id, family=None):
    """Find core scores file for a protein."""
    base_dir = Path("/storage/kiran-stuff/RAA")

    # search locations in order of preference
    search_paths = []

    # 1. ultimate test set (has family prefix)
    uts_dir = base_dir / "ultimate_test_set" / "core_scores"
    if uts_dir.exists():
        for f in uts_dir.glob(f"*_{protein_id}_core.csv"):
            search_paths.append(f)

    # 2. family-specific directory
    if family:
        family_file = base_dir / family / "family_core_scores.csv"
        if family_file.exists():
            search_paths.append(("family_csv", family_file, protein_id))

    # 3. search all PF* directories for family_core_scores.csv
    for pf_dir in base_dir.glob("PF*"):
        family_file = pf_dir / "family_core_scores.csv"
        if family_file.exists():
            search_paths.append(("family_csv", family_file, protein_id))

    return search_paths

def load_core_scores(protein_id, family=None):
    """Load core scores for a protein."""
    search_paths = find_core_scores(protein_id, family)

    for path_info in search_paths:
        try:
            if isinstance(path_info, tuple) and path_info[0] == "family_csv":
                # load from family_core_scores.csv
                _, csv_path, pid = path_info
                df = pd.read_csv(csv_path)
                protein_df = df[df['protein_id'] == pid]
                if len(protein_df) > 0:
                    print(f"Loaded {len(protein_df)} residues from {csv_path}")
                    return protein_df
            else:
                # load individual core file
                df = pd.read_csv(path_info)
                print(f"Loaded {len(df)} residues from {path_info}")
                return df
        except Exception as e:
            continue

    return None

def generate_pymol_script(protein_id, core_df, pdb_path=None):
    """Generate PyMOL visualization script."""

    # identify core vs non-core positions
    core_positions = core_df[core_df['core_score'] >= EFS_CORE_THRESHOLD]['pdb_resnum'].tolist()
    noncore_positions = core_df[core_df['core_score'] < EFS_CORE_THRESHOLD]['pdb_resnum'].tolist()

    # get amino acid breakdown for core
    core_aas = core_df[core_df['core_score'] >= EFS_CORE_THRESHOLD]['aa'].value_counts()

    # build pymol script
    lines = [
        f"# EFS Core Visualization for {protein_id}",
        f"# Generated by visualize_efs.py",
        f"#",
        f"# EFS Core Definition: core_score >= {EFS_CORE_THRESHOLD} (C20)",
        f"# Core positions: {len(core_positions)} ({len(core_positions)/len(core_df)*100:.1f}%)",
        f"# Non-core positions: {len(noncore_positions)} ({len(noncore_positions)/len(core_df)*100:.1f}%)",
        f"#",
        "",
    ]

    # load structure if path provided
    if pdb_path:
        lines.append(f"load {pdb_path}")
        lines.append("")

    lines.extend([
        "# setup",
        "bg_color white",
        "hide everything",
        "show cartoon",
        "color gray80, all",
        "",
        "# === EFS CORE (RED) ===",
        "# these positions are critical for folding stability",
        "# they should be PRESERVED in any RAA reduction",
    ])

    if core_positions:
        pos_str = "+".join(str(p) for p in sorted(core_positions))
        lines.extend([
            f"select efs_core, resi {pos_str}",
            "color red, efs_core",
            "show sticks, efs_core and (not name c+n+o)",
            "",
        ])

    lines.extend([
        "# === NON-CORE (BLUE) ===",
        "# these positions can be reduced to simplified alphabet",
    ])

    if noncore_positions:
        pos_str = "+".join(str(p) for p in sorted(noncore_positions))
        lines.extend([
            f"select non_core, resi {pos_str}",
            "color skyblue, non_core",
            "",
        ])

    # highlight cysteines specifically (important for EFS)
    cys_positions = core_df[core_df['aa'] == 'C']['pdb_resnum'].tolist()
    if cys_positions:
        pos_str = "+".join(str(p) for p in sorted(cys_positions))
        lines.extend([
            "# === CYSTEINES (YELLOW STICKS) ===",
            "# cysteines get special scoring in EFS",
            f"select cysteines, resi {pos_str}",
            "show sticks, cysteines",
            "color yellow, cysteines",
            "",
        ])

    lines.extend([
        "# cleanup",
        "deselect",
        "zoom",
        "",
        "# === LEGEND ===",
        f"# RED    = EFS Core ({len(core_positions)} positions) - PRESERVE",
        f"# BLUE   = Non-core ({len(noncore_positions)} positions) - CAN REDUCE",
        f"# YELLOW = Cysteines ({len(cys_positions)} positions) - SPECIAL",
        "",
        "# === CORE AA COMPOSITION ===",
    ])

    for aa, count in core_aas.head(10).items():
        lines.append(f"# {aa}: {count} ({count/len(core_positions)*100:.1f}%)")

    return "\n".join(lines)

def generate_chimerax_script(protein_id, core_df, pdb_path=None):
    """Generate ChimeraX visualization script."""

    core_positions = core_df[core_df['core_score'] >= EFS_CORE_THRESHOLD]['pdb_resnum'].tolist()
    noncore_positions = core_df[core_df['core_score'] < EFS_CORE_THRESHOLD]['pdb_resnum'].tolist()
    cys_positions = core_df[core_df['aa'] == 'C']['pdb_resnum'].tolist()

    lines = [
        f"# EFS Core Visualization for {protein_id}",
        f"# ChimeraX script",
        "",
    ]

    if pdb_path:
        lines.append(f"open {pdb_path}")
        lines.append("")

    lines.extend([
        "# setup",
        "preset original",
        "color gray",
        "",
    ])

    if core_positions:
        pos_str = ",".join(str(p) for p in sorted(core_positions))
        lines.extend([
            f"# EFS core (red)",
            f"color :{pos_str} red",
            "",
        ])

    if noncore_positions:
        pos_str = ",".join(str(p) for p in sorted(noncore_positions))
        lines.extend([
            f"# non-core (blue)",
            f"color :{pos_str} cornflower blue",
            "",
        ])

    if cys_positions:
        pos_str = ",".join(str(p) for p in sorted(cys_positions))
        lines.extend([
            f"# cysteines (yellow)",
            f"show :{pos_str} atoms",
            f"color :{pos_str} yellow",
            "",
        ])

    lines.extend([
        f"# LEGEND:",
        f"# RED = EFS Core ({len(core_positions)} positions)",
        f"# BLUE = Non-core ({len(noncore_positions)} positions)",
        f"# YELLOW = Cysteines ({len(cys_positions)} positions)",
    ])

    return "\n".join(lines)

def find_pdb_file(protein_id, family=None):
    """Try to find the PDB file for a protein."""
    base_dir = Path("/storage/kiran-stuff/RAA")

    # search patterns
    patterns = [
        f"**/{protein_id}.pdb",
        f"**/{protein_id}_*.pdb",
        f"**/native_structures/{protein_id}*.pdb",
        f"**/structures/{protein_id}*.pdb",
    ]

    if family:
        for pattern in [f"{family}/**/{protein_id}*.pdb", f"{family}/native_structures/{protein_id}*.pdb"]:
            matches = list(base_dir.glob(pattern))
            if matches:
                return matches[0]

    for pattern in patterns:
        matches = list(base_dir.glob(pattern))
        if matches:
            return matches[0]

    return None

def main():
    parser = argparse.ArgumentParser(description="Generate EFS visualization scripts")
    parser.add_argument("protein_id", help="Protein ID (e.g., A2QRF6)")
    parser.add_argument("--family", "-f", help="Pfam family (e.g., PF00069)")
    parser.add_argument("--pdb", "-p", help="Path to PDB file")
    parser.add_argument("--output", "-o", default="pymol_viz", help="Output directory")

    args = parser.parse_args()

    print(f"EFS Core Visualization Protocol")
    print(f"================================")
    print(f"Protein: {args.protein_id}")
    print(f"Family: {args.family or 'auto-detect'}")
    print()

    # load core scores
    core_df = load_core_scores(args.protein_id, args.family)

    if core_df is None:
        print(f"ERROR: Could not find core scores for {args.protein_id}")
        print(f"Try specifying --family PF00069 or another family")
        sys.exit(1)

    # find pdb file
    pdb_path = args.pdb
    if not pdb_path:
        pdb_path = find_pdb_file(args.protein_id, args.family)
        if pdb_path:
            print(f"Found PDB: {pdb_path}")

    # create output directory
    out_dir = Path(args.output)
    out_dir.mkdir(exist_ok=True)

    # generate scripts
    pymol_script = generate_pymol_script(args.protein_id, core_df, pdb_path)
    chimerax_script = generate_chimerax_script(args.protein_id, core_df, pdb_path)

    # save scripts
    pymol_file = out_dir / f"{args.protein_id}_efs.pml"
    chimerax_file = out_dir / f"{args.protein_id}_efs.cxc"

    with open(pymol_file, 'w') as f:
        f.write(pymol_script)
    print(f"Created: {pymol_file}")

    with open(chimerax_file, 'w') as f:
        f.write(chimerax_script)
    print(f"Created: {chimerax_file}")

    # summary
    n_core = (core_df['core_score'] >= EFS_CORE_THRESHOLD).sum()
    n_total = len(core_df)

    print()
    print(f"=== SUMMARY ===")
    print(f"Total residues: {n_total}")
    print(f"EFS Core (≥C20): {n_core} ({n_core/n_total*100:.1f}%)")
    print(f"Non-core: {n_total - n_core} ({(n_total-n_core)/n_total*100:.1f}%)")
    print()
    print(f"=== USAGE ===")
    print(f"PyMOL:    load structure.pdb; @{pymol_file}")
    print(f"ChimeraX: open structure.pdb; open {chimerax_file}")

if __name__ == "__main__":
    main()
