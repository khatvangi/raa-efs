#!/usr/bin/env python3
"""
EFS Superimposition Visualization
==================================
Creates PyMOL scripts showing native vs EFS-reduced structure superimposition.

This is the "hero figure" for visualizing ESMFold validation.

Usage:
    python visualize_superimpose.py <protein_id> [--family PF00069] [--variant EFS_C20_RAA10]

Example:
    python visualize_superimpose.py A2QRF6 --family PF00069 --variant EFS_C20_RAA10

Output:
    pymol_viz/<protein>_superimpose.pml - PyMOL script
    pymol_viz/<protein>_superimpose.cxc - ChimeraX script
"""

import pandas as pd
import argparse
import os
import sys
import subprocess
from pathlib import Path

# efs core threshold
EFS_CORE_THRESHOLD = 20

def find_native_pdb(protein_id, family=None):
    """Find native PDB structure."""
    base_dir = Path("/storage/kiran-stuff/RAA")

    search_patterns = []

    if family:
        # family-specific locations
        search_patterns.extend([
            base_dir / family / "Original" / f"{protein_id}.pdb",
            base_dir / family / "native_structures" / f"{protein_id}.pdb",
            base_dir / family / "EFS_C_structures" / f"{protein_id}.pdb",
            base_dir / family / f"{protein_id}.pdb",
        ])

    # ultimate test set
    for pf in base_dir.glob("PF*"):
        search_patterns.append(pf / "native_structures" / f"{protein_id}.pdb")
        search_patterns.append(pf / "Original" / f"{protein_id}.pdb")

    for path in search_patterns:
        if path.exists():
            return path

    return None

def find_variant_pdb(protein_id, variant, family=None):
    """Find EFS-reduced variant PDB structure."""
    base_dir = Path("/storage/kiran-stuff/RAA")

    # construct variant filename
    variant_name = f"{protein_id}_{variant}.pdb"

    search_patterns = []

    if family:
        search_patterns.extend([
            base_dir / family / "EFS_C_structures" / variant_name,
            base_dir / family / "structures" / variant_name,
            base_dir / family / variant_name,
        ])

    # search all PF* directories
    for pf in base_dir.glob("PF*"):
        search_patterns.append(pf / "EFS_C_structures" / variant_name)

    for path in search_patterns:
        if path.exists():
            return path

    return None

def find_available_variants(protein_id, family=None):
    """List available variants for a protein."""
    base_dir = Path("/storage/kiran-stuff/RAA")

    variants = []

    if family:
        efs_dir = base_dir / family / "EFS_C_structures"
        if efs_dir.exists():
            for f in efs_dir.glob(f"{protein_id}_*.pdb"):
                # extract variant name: A2QRF6_EFS_C20_RAA10.pdb -> EFS_C20_RAA10
                variant = f.stem.replace(f"{protein_id}_", "")
                if variant != protein_id:
                    variants.append(variant)

    return sorted(set(variants))

def load_core_scores(protein_id, family=None):
    """Load core scores for a protein."""
    base_dir = Path("/storage/kiran-stuff/RAA")

    # try ultimate test set first
    uts_dir = base_dir / "ultimate_test_set" / "core_scores"
    if uts_dir.exists():
        for f in uts_dir.glob(f"*_{protein_id}_core.csv"):
            try:
                return pd.read_csv(f)
            except:
                pass

    # try family_core_scores.csv
    if family:
        family_file = base_dir / family / "family_core_scores.csv"
        if family_file.exists():
            df = pd.read_csv(family_file)
            protein_df = df[df['protein_id'] == protein_id]
            if len(protein_df) > 0:
                return protein_df

    return None

def run_usalign(native_pdb, variant_pdb):
    """Run USalign to get TM-score."""
    usalign_path = "/storage/kiran-stuff/US-align/USalign"

    if not os.path.exists(usalign_path):
        return None

    try:
        result = subprocess.run(
            [usalign_path, str(variant_pdb), str(native_pdb)],
            capture_output=True, text=True, timeout=60
        )

        # parse TM-score from output
        for line in result.stdout.split('\n'):
            if 'TM-score=' in line and 'Chain_1' in line:
                # TM-score= 0.85234 (normalized by length of Chain_1)
                tm = float(line.split('TM-score=')[1].split()[0])
                return tm
    except:
        pass

    return None

def generate_pymol_superimpose_script(protein_id, native_pdb, variant_pdb, variant_name, core_df=None, tm_score=None):
    """Generate PyMOL superimposition script."""

    lines = [
        f"# EFS Superimposition Visualization for {protein_id}",
        f"# Native vs {variant_name}",
        f"#",
        f"# Generated by visualize_superimpose.py",
    ]

    if tm_score:
        lines.append(f"# TM-score: {tm_score:.3f}")

    lines.extend([
        "#",
        "",
        "# === LOAD STRUCTURES ===",
        f"load {native_pdb}, native",
        f"load {variant_pdb}, reduced",
        "",
        "# === SETUP ===",
        "bg_color white",
        "hide everything",
        "",
        "# === ALIGN STRUCTURES ===",
        "# align reduced to native (CEalign for structural alignment)",
        "cealign native, reduced",
        "",
        "# === DISPLAY ===",
        "# show both as cartoon",
        "show cartoon, native",
        "show cartoon, reduced",
        "",
        "# === COLOR SCHEME ===",
        "# native: gray (reference)",
        "color gray70, native",
        "",
        "# reduced: color by region",
    ])

    if core_df is not None:
        core_positions = core_df[core_df['core_score'] >= EFS_CORE_THRESHOLD]['pdb_resnum'].tolist()
        noncore_positions = core_df[core_df['core_score'] < EFS_CORE_THRESHOLD]['pdb_resnum'].tolist()

        if core_positions:
            pos_str = "+".join(str(p) for p in sorted(core_positions))
            lines.extend([
                f"# EFS core (preserved) - GREEN (success!)",
                f"select reduced_core, reduced and resi {pos_str}",
                "color green, reduced_core",
                "",
            ])

        if noncore_positions:
            pos_str = "+".join(str(p) for p in sorted(noncore_positions))
            lines.extend([
                f"# non-core (reduced alphabet) - CYAN",
                f"select reduced_noncore, reduced and resi {pos_str}",
                "color cyan, reduced_noncore",
                "",
            ])
    else:
        lines.extend([
            "# no core data - color entire reduced structure",
            "color splitpea, reduced",
            "",
        ])

    lines.extend([
        "# === HIGHLIGHT DEVIATIONS ===",
        "# show sticks for reduced structure to see side chains",
        "# (optional - uncomment to see side chain conformations)",
        "# show sticks, reduced and (not name c+n+o)",
        "",
        "# === TRANSPARENCY ===",
        "# make native semi-transparent to see overlap",
        "set cartoon_transparency, 0.5, native",
        "",
        "# === FINAL SETUP ===",
        "deselect",
        "zoom",
        "center",
        "",
        "# === VIEWS FOR PUBLICATION ===",
        "# rotate to show key features",
        "# orient",
        "",
        "# === LEGEND ===",
        f"# GRAY (transparent) = Native structure",
    ])

    if core_df is not None:
        n_core = len(core_positions) if core_positions else 0
        n_noncore = len(noncore_positions) if noncore_positions else 0
        lines.extend([
            f"# GREEN = EFS Core preserved ({n_core} positions)",
            f"# CYAN = Non-core reduced ({n_noncore} positions)",
        ])
    else:
        lines.append("# GREEN = EFS-reduced structure")

    if tm_score:
        lines.extend([
            "",
            f"# === VALIDATION ===",
            f"# TM-score: {tm_score:.3f}",
            f"# {'PASS' if tm_score >= 0.7 else 'FAIL'} (threshold: 0.7)",
        ])

    lines.extend([
        "",
        "# === SAVE IMAGE ===",
        f"# ray 2400, 2400",
        f"# png {protein_id}_{variant_name}_superimpose.png, dpi=300",
    ])

    return "\n".join(lines)

def generate_chimerax_superimpose_script(protein_id, native_pdb, variant_pdb, variant_name, core_df=None, tm_score=None):
    """Generate ChimeraX superimposition script."""

    lines = [
        f"# EFS Superimposition for {protein_id}",
        f"# Native vs {variant_name}",
    ]

    if tm_score:
        lines.append(f"# TM-score: {tm_score:.3f}")

    lines.extend([
        "",
        f"# load structures",
        f"open {native_pdb}",
        f"open {variant_pdb}",
        "",
        "# align",
        "matchmaker #2 to #1",
        "",
        "# color native gray",
        "color #1 gray",
        "transparency #1 50 cartoon",
        "",
    ])

    if core_df is not None:
        core_positions = core_df[core_df['core_score'] >= EFS_CORE_THRESHOLD]['pdb_resnum'].tolist()
        noncore_positions = core_df[core_df['core_score'] < EFS_CORE_THRESHOLD]['pdb_resnum'].tolist()

        if core_positions:
            pos_str = ",".join(str(p) for p in sorted(core_positions))
            lines.extend([
                f"# EFS core (green)",
                f"color #2:{pos_str} green",
            ])

        if noncore_positions:
            pos_str = ",".join(str(p) for p in sorted(noncore_positions))
            lines.extend([
                f"# non-core (cyan)",
                f"color #2:{pos_str} cyan",
            ])
    else:
        lines.append("color #2 forest green")

    lines.extend([
        "",
        "# final setup",
        "view",
    ])

    return "\n".join(lines)

def generate_comparison_panel_script(protein_id, native_pdb, variant_pdb, variant_name, core_df=None, tm_score=None):
    """Generate PyMOL script for side-by-side comparison (better for publication)."""

    lines = [
        f"# Side-by-Side Comparison Panel for {protein_id}",
        f"# Native (left) vs {variant_name} (right)",
        f"#",
    ]

    if tm_score:
        lines.append(f"# TM-score: {tm_score:.3f}")

    lines.extend([
        "#",
        "",
        "# === LOAD AND SETUP ===",
        f"load {native_pdb}, native",
        f"load {variant_pdb}, reduced",
        "",
        "bg_color white",
        "hide everything",
        "",
        "# align first",
        "cealign native, reduced",
        "",
        "# === NATIVE STRUCTURE (will be on left) ===",
        "show cartoon, native",
    ])

    if core_df is not None:
        core_positions = core_df[core_df['core_score'] >= EFS_CORE_THRESHOLD]['pdb_resnum'].tolist()
        noncore_positions = core_df[core_df['core_score'] < EFS_CORE_THRESHOLD]['pdb_resnum'].tolist()

        if core_positions:
            pos_str = "+".join(str(p) for p in sorted(core_positions))
            lines.extend([
                f"select native_core, native and resi {pos_str}",
                "color firebrick, native_core",
            ])

        if noncore_positions:
            pos_str = "+".join(str(p) for p in sorted(noncore_positions))
            lines.extend([
                f"select native_noncore, native and resi {pos_str}",
                "color skyblue, native_noncore",
            ])
    else:
        lines.append("color gray70, native")

    lines.extend([
        "",
        "# === REDUCED STRUCTURE (will be on right) ===",
        "show cartoon, reduced",
    ])

    if core_df is not None:
        if core_positions:
            pos_str = "+".join(str(p) for p in sorted(core_positions))
            lines.extend([
                f"select reduced_core, reduced and resi {pos_str}",
                "color firebrick, reduced_core",
            ])

        if noncore_positions:
            pos_str = "+".join(str(p) for p in sorted(noncore_positions))
            lines.extend([
                f"select reduced_noncore, reduced and resi {pos_str}",
                "color skyblue, reduced_noncore",
            ])
    else:
        lines.append("color splitpea, reduced")

    lines.extend([
        "",
        "# === POSITION SIDE BY SIDE ===",
        "# translate reduced to the right",
        "translate [80, 0, 0], reduced",
        "",
        "# === CLEANUP ===",
        "deselect",
        "zoom",
        "",
        "# === LEGEND ===",
        "# LEFT = Native structure",
        "# RIGHT = EFS-reduced structure",
        "# RED = EFS Core positions (preserved)",
        "# BLUE = Non-core positions (reduced alphabet)",
    ])

    if tm_score:
        lines.append(f"# TM-score: {tm_score:.3f}")

    lines.extend([
        "",
        "# === SAVE ===",
        f"# ray 3200, 1600",
        f"# png {protein_id}_{variant_name}_comparison.png, dpi=300",
    ])

    return "\n".join(lines)

def main():
    parser = argparse.ArgumentParser(description="Generate EFS superimposition visualization")
    parser.add_argument("protein_id", help="Protein ID (e.g., A2QRF6)")
    parser.add_argument("--family", "-f", default="PF00069", help="Pfam family (default: PF00069)")
    parser.add_argument("--variant", "-v", default="EFS_C20_RAA10", help="Variant name (default: EFS_C20_RAA10)")
    parser.add_argument("--output", "-o", default="pymol_viz", help="Output directory")
    parser.add_argument("--list-variants", "-l", action="store_true", help="List available variants")

    args = parser.parse_args()

    print(f"EFS Superimposition Visualization")
    print(f"==================================")
    print(f"Protein: {args.protein_id}")
    print(f"Family: {args.family}")
    print()

    # list variants if requested
    if args.list_variants:
        variants = find_available_variants(args.protein_id, args.family)
        if variants:
            print(f"Available variants for {args.protein_id}:")
            for v in variants[:20]:
                print(f"  - {v}")
            if len(variants) > 20:
                print(f"  ... and {len(variants) - 20} more")
        else:
            print("No variants found")
        return

    # find native structure
    native_pdb = find_native_pdb(args.protein_id, args.family)
    if not native_pdb:
        print(f"ERROR: Could not find native PDB for {args.protein_id}")
        sys.exit(1)
    print(f"Native: {native_pdb}")

    # find variant structure
    variant_pdb = find_variant_pdb(args.protein_id, args.variant, args.family)
    if not variant_pdb:
        print(f"ERROR: Could not find variant {args.variant} for {args.protein_id}")
        print(f"Try: python visualize_superimpose.py {args.protein_id} --list-variants")
        sys.exit(1)
    print(f"Variant: {variant_pdb}")

    # load core scores
    core_df = load_core_scores(args.protein_id, args.family)
    if core_df is not None:
        n_core = (core_df['core_score'] >= EFS_CORE_THRESHOLD).sum()
        print(f"Core scores: {len(core_df)} residues, {n_core} core")
    else:
        print("Core scores: not found (will use simple coloring)")

    # run USalign to get TM-score
    print("\nRunning USalign...")
    tm_score = run_usalign(native_pdb, variant_pdb)
    if tm_score:
        status = "PASS ✓" if tm_score >= 0.7 else "FAIL ✗"
        print(f"TM-score: {tm_score:.3f} ({status})")
    else:
        print("TM-score: could not compute")

    # create output directory
    out_dir = Path(args.output)
    out_dir.mkdir(exist_ok=True)

    # generate scripts
    print("\nGenerating visualization scripts...")

    # 1. superimposition (overlay)
    pymol_super = generate_pymol_superimpose_script(
        args.protein_id, native_pdb, variant_pdb, args.variant, core_df, tm_score
    )
    super_file = out_dir / f"{args.protein_id}_{args.variant}_superimpose.pml"
    with open(super_file, 'w') as f:
        f.write(pymol_super)
    print(f"  Created: {super_file}")

    # 2. side-by-side comparison
    pymol_panel = generate_comparison_panel_script(
        args.protein_id, native_pdb, variant_pdb, args.variant, core_df, tm_score
    )
    panel_file = out_dir / f"{args.protein_id}_{args.variant}_sidebyside.pml"
    with open(panel_file, 'w') as f:
        f.write(pymol_panel)
    print(f"  Created: {panel_file}")

    # 3. ChimeraX version
    chimerax_super = generate_chimerax_superimpose_script(
        args.protein_id, native_pdb, variant_pdb, args.variant, core_df, tm_score
    )
    cxc_file = out_dir / f"{args.protein_id}_{args.variant}_superimpose.cxc"
    with open(cxc_file, 'w') as f:
        f.write(chimerax_super)
    print(f"  Created: {cxc_file}")

    # summary
    print()
    print("=" * 50)
    print("VISUALIZATION SCRIPTS READY")
    print("=" * 50)
    print()
    print("For OVERLAY view (structures superimposed):")
    print(f"  PyMOL:    @{super_file}")
    print()
    print("For SIDE-BY-SIDE view (native left, reduced right):")
    print(f"  PyMOL:    @{panel_file}")
    print()
    print("For ChimeraX:")
    print(f"  open {cxc_file}")
    print()
    print("Color scheme:")
    print("  GRAY (transparent) = Native structure")
    print("  RED/FIREBRICK = EFS Core (preserved)")
    print("  BLUE/CYAN = Non-core (reduced alphabet)")
    if tm_score:
        print()
        print(f"Validation: TM-score = {tm_score:.3f} ({'PASS' if tm_score >= 0.7 else 'FAIL'})")

if __name__ == "__main__":
    main()
